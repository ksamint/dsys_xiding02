// QR Code encoder (ISO/IEC 18004), byte mode, UTF-8. After Project Nayuki's reference design.
// No dependencies; returns the module matrix, quiet zone not included.

export type Ecl = "L" | "M" | "Q" | "H";

export interface QrMatrix {
  version: number;
  size: number;
  /** modules[y][x], true is dark. */
  modules: boolean[][];
}

const ECL_ORD: Record<Ecl, number> = { L: 0, M: 1, Q: 2, H: 3 };
const ECL_FORMAT: Record<Ecl, number> = { L: 1, M: 0, Q: 3, H: 2 };

