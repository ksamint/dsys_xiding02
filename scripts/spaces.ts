import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/* Takes the bookable spaces out of the space ledger (西顶庙 · 空间台账与坪效) and writes them to
   src/shared/spaces-ledger.ts, so the app shows the ledger's names, uses, areas and capacities.
     npx tsx scripts/spaces.ts <saved ledger page.html>
   The ledger keeps its edits in its reader's browser; until it publishes its data to the one source of truth, run
   this again whenever it changes. Capacity follows the ledger's own rule: usable area (area × the kind's usable
   share) over the area one person needs in the space's layout. */

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

import { DENSITY, USABLE, type Setup } from "../src/shared/setups";

interface LedgerSpace {
  code: string;
  name: string | null;
  use: string | null;
  zone: string;
  kind: string;
  layout: string | null;
  area: number;
  confirmed: boolean;
  parts?: { area: number }[];
}

export interface SpaceRow {
  readonly code: string;
  readonly name: string;
  readonly use: string;
  readonly zone: string;
  readonly kind: "hall" | "room" | "gallery" | "courtyard";
  readonly layout: Setup;
  readonly area: number;
  /** The floor its seats are counted from: the main part of a merged hall, otherwise the whole area. */
  readonly floor: number;
  readonly capacity: number;
}

export function bookable(spaces: readonly LedgerSpace[]): SpaceRow[] {
  return spaces
    .filter((s) => s.confirmed && s.name && s.layout && s.layout in DENSITY && s.kind in USABLE)
    .map((s) => {
      // A merged hall seats people in its main part only, as the ledger notes.
      const floor = s.kind === "hall" && s.parts && s.parts.length > 1 ? (s.parts[0]?.area ?? s.area) : s.area;
      const kind = s.kind as SpaceRow["kind"];
      const layout = s.layout as Setup;
      const capacity = Math.floor((floor * USABLE[kind]) / DENSITY[layout]);
      return { code: s.code, name: s.name ?? s.code, use: s.use ?? "", zone: s.zone, kind, layout, area: s.area, floor, capacity };
    });
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const file = process.argv[2];
  if (!file) throw new Error("Give the saved ledger page: npx tsx scripts/spaces.ts <page.html>");
  const html = await readFile(file, "utf8");
  const start = html.indexOf("const XD_DATA = ");
  if (start < 0) throw new Error("No XD_DATA in that page");
  const line = html.slice(start + "const XD_DATA = ".length, html.indexOf("\n", start)).replace(/;\s*$/, "");
  const data = JSON.parse(line) as { spaces: LedgerSpace[] };
  const rows = bookable(data.spaces);
  const out = `/* Generated by scripts/spaces.ts from the space ledger (西顶庙 · 空间台账与坪效). Do not edit by hand. */
import type { SpaceRow } from "../../scripts/spaces";

export const LEDGER: readonly SpaceRow[] = ${JSON.stringify(rows, null, 2)};
`;
  await writeFile(join(ROOT, "src", "shared", "spaces-ledger.ts"), out);
  console.log(`spaces: ${rows.length} bookable spaces of ${data.spaces.length} written to src/shared/spaces-ledger.ts`);
}
